/**
 * Deterministic keyword search over SUPPORT_KB.
 */
const STOP_WORDS = new Set(['hop', 'why', 'did', 'does', 'how', 'what', 'when', 'where', 'the', 'and', 'for', 'you', 'can', 'with', 'say', 'says'])

export function searchSupportKb(query: string, limit = 3): KbEntry[] {
  if (!query || !query.trim()) return []
  const terms = query
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .split(/\s+/)
    .filter((t) => t.length > 2 && !STOP_WORDS.has(t))

  if (terms.length === 0) return []

  const scored = SUPPORT_KB.map((entry) => {
    const text = `${entry.title} ${entry.body}`.toLowerCase()
    let score = 0
    for (const term of terms) {
      if (entry.title.toLowerCase().includes(term)) score += 3
      if (text.includes(term)) score += 1
    }
    return { entry, score }
  })

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((s) => s.entry)
}

/**
 * Deterministic, no-LLM fallback answer.
 * Guaranteed to contain zero economic numbers (¢/pt, $, miles, etc.).
 */
export function fallbackSupportAnswer(query: string): string {
  const hits = searchSupportKb(query, 1)
  const best = hits.length > 0 ? hits[0] : SUPPORT_KB[0]
  return `${best.body}\n\nFor details, see /support#${best.anchor} or email support@hop.flights.`
}
